def test_to_html_fragment_ignores_style(valid_document_record_1, tmp_path):
    """A fragment has no stylesheet, so 'style' is neither checked nor read from disk."""
    css_file = tmp_path / "theme.css"
    css_file.write_text("body { color: red; }", encoding="utf-8")

    with patch("dorsal_adapters.document.html_adapter.exporter.open") as mock_open:
        result = to_html(valid_document_record_1, validate=False, fragment=True, style=str(css_file))

    mock_open.assert_not_called()
    assert "color: red" not in result
    assert result == to_html(valid_document_record_1, validate=False, fragment=True)


def test_to_html_style_and_style_path_conflict(valid_document_record_1, tmp_path):
    """'style' and 'style_path' can't both be given."""
    css_file = tmp_path / "theme.css"
    css_file.write_text("body { color: red; }", encoding="utf-8")

    with pytest.raises(ValueError, match="either 'style' or 'style_path'"):
        to_html(valid_document_record_1, validate=False, style="dark", style_path=css_file)


