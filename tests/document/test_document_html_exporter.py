class _MarkupCollector(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.tags: list[str] = []
        self.attr_names: set[str] = set()
        self.attr_values: dict[str, list[str | None]] = {}

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.tags.append(tag)
        for name, value in attrs:
            self.attr_names.add(name)
            self.attr_values.setdefault(name, []).append(value)


def _collect(markup: str) -> _MarkupCollector:
    collector = _MarkupCollector()
    collector.feed(markup)
    collector.close()
    return collector


HOSTILE_MARKUP = '<b id="injected">x</b>'
HOSTILE_ATTRIBUTE = '" data-injected="1'


def _hostile_record() -> dict:
    return {
        "extraction_type": "mixed",
        "unit": "px",
        "blocks": [
            {
                "block_type": "text",
                "text": HOSTILE_MARKUP + HOSTILE_ATTRIBUTE,
                "page_number": 1,
                "box": {"x": 10, "y": 10, "width": 100, "height": 20},
            },
            {
                "block_type": HOSTILE_MARKUP + HOSTILE_ATTRIBUTE,
                "page_number": 1,
                "box": {"x": 10, "y": 300, "width": 100, "height": 100},
            },
            {
                "block_type": "text",
                "text": "Second page",
                "page_number": HOSTILE_MARKUP + HOSTILE_ATTRIBUTE,
                "box": {"x": 10, "y": 10, "width": 100, "height": 20},
            },
        ],
    }


def _assert_no_injected_markup(result: str) -> None:
    collector = _collect(result)
    assert "b" not in collector.tags
    assert "injected" not in collector.attr_values.get("id", [])
    assert "data-injected" not in collector.attr_names


@pytest.mark.parametrize("layout", ["col", "grid", "wireframe"])
@pytest.mark.parametrize("style", ["default", "dark", "none"])
@pytest.mark.parametrize("fragment", [False, True])
def test_to_html_escapes_record_fields_and_footer(layout, style, fragment):
    """Record fields and the footer are rendered as text in every layout and theme."""
    result = to_html(
        _hostile_record(),
        validate=False,
        layout=layout,
        style=style,
        fragment=fragment,
        footer=HOSTILE_MARKUP + HOSTILE_ATTRIBUTE,
    )

    _assert_no_injected_markup(result)
    assert "&lt;b id=&quot;injected&quot;&gt;" in result
    assert '<div class="document-footer">\n    &lt;b id=&quot;injected&quot;&gt;' in result
    assert '<div class="page-divider">Page &lt;b id=&quot;injected&quot;&gt;' in result
    if layout != "wireframe":
        assert '<div class="figure-placeholder">[&lt;b id=&quot;injected&quot;&gt;' in result


def test_to_html_footer_on_empty_record_is_escaped():
    """The footer of a record with no content is rendered as text."""
    result = to_html({"blocks": []}, validate=False, footer=HOSTILE_MARKUP)

    _assert_no_injected_markup(result)


def test_to_html_footer_accepts_non_string_values(valid_document_record_1):
    """A footer given as a number, as CLI options can be, is rendered as text."""
    result = to_html(valid_document_record_1, validate=False, footer=2026)  # type: ignore[arg-type]

    assert '<div class="document-footer">\n    2026\n  </div>' in result


def test_to_html_style_path_cannot_close_the_style_element(valid_document_record_1, tmp_path):
    """A stylesheet's contents stay inside the page's style element."""
    css_file = tmp_path / "theme.css"
    css_file.write_text(f"body {{ color: red; }}</STYLE>{HOSTILE_MARKUP}", encoding="utf-8")

    result = to_html(valid_document_record_1, validate=False, style_path=str(css_file))

    _assert_no_injected_markup(result)
    assert "body { color: red; }<\\/STYLE>" in result
    assert result.lower().count("</style") == 1


@pytest.mark.parametrize("exists", [True, False])
def test_to_html_style_path_given_as_style_raises(valid_document_record_1, tmp_path, exists):
    """A file path passed as 'style' raises, names 'style_path', and is never opened."""
    css_file = tmp_path / "theme.css"
    if exists:
        css_file.write_text("body { color: red; }", encoding="utf-8")

    with (
        patch("dorsal_adapters.document.html_adapter.exporter.open") as mock_open,
        patch("os.path.isfile") as mock_isfile,
        pytest.raises(ValueError, match="style_path"),
    ):
        to_html(valid_document_record_1, validate=False, style=str(css_file))

    mock_open.assert_not_called()
    mock_isfile.assert_not_called()


